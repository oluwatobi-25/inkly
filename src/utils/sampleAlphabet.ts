/**
 * Returns a deep copy of sample glyphs for given characters.
 */
export function getSampleGlyphs(): Record<string, Stroke[]> {
  const result: Record<string, Stroke[]> = {};
  for (const char in SAMPLE_UPPERCASE_STROKES) {
    result[char] = JSON.parse(JSON.stringify(SAMPLE_UPPERCASE_STROKES[char]));
  }
  for (const char in SAMPLE_LOWERCASE_STROKES) {
    result[char] = JSON.parse(JSON.stringify(SAMPLE_LOWERCASE_STROKES[char]));
  }
  for (const char in SAMPLE_NUMBER_STROKES) {
    result[char] = JSON.parse(JSON.stringify(SAMPLE_NUMBER_STROKES[char]));
  }
  return result;
}
