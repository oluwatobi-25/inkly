import { Stroke, Point } from '../types/font';

function addJitter(points: Point[], jitter = 1.2): Point[] {
  return points.map((p, i) => {
    // slight natural hand wobble
    const wobbleX = (Math.sin(i * 1.7) * jitter);
    const wobbleY = (Math.cos(i * 1.3) * (jitter * 0.8));
    return {
      x: p.x + wobbleX,
      y: p.y + wobbleY,
      pressure: 0.5 + Math.sin(i * 0.5) * 0.15,
    };
  });
}

function makeStroke(rawPoints: [number, number][], color = '#19191C', width = 6): Stroke {
  const points = rawPoints.map(([x, y]) => ({ x, y }));
  return {
    points: addJitter(points),
    color,
    width,
  };
}

